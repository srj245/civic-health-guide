import {
  Dialog,
  DialogContent,
  DialogHeader,
  DialogTitle,
} from "@/components/ui/dialog";
import { Badge } from "@/components/ui/badge";
import { Skeleton } from "@/components/ui/skeleton";
import { useBillDetails, type Bill } from "@/hooks/useCongressApi";
import { useBillSummary } from "@/hooks/useBillSummary";
import { useTrackedBills } from "@/hooks/useTrackedBills";
import { useAuth } from "@/hooks/useAuth";
import { Calendar, FileText, Users, ExternalLink, Sparkles, Share2, Bookmark, Printer } from "lucide-react";
import { Button } from "@/components/ui/button";
import { useEffect } from "react";
import { useToast } from "@/hooks/use-toast";
import BillDiscussion from "./BillDiscussion";
import { escapeHtml, ordinal } from "@/lib/format";

interface BillDetailModalProps {
  bill: Bill | null;
  open: boolean;
  onOpenChange: (open: boolean) => void;
}

function stripHtml(html: string): string {
  return html.replace(/<[^>]*>/g, '').trim();
}

const BillDetailModal = ({ bill, open, onOpenChange }: BillDetailModalProps) => {
  const { bill: details, loading, error } = useBillDetails(bill?.id || null);
  const { summary: aiSummary, loading: aiLoading, error: aiError, summarize } = useBillSummary();
  const { toggleTrack, isTracked } = useTrackedBills();
  const { user } = useAuth();
  const { toast } = useToast();

  // Auto-generate AI summary when details load
  useEffect(() => {
    if (details && open) {
      summarize(
        details.title || bill?.title || '',
        details.summary ? stripHtml(details.summary) : undefined,
        details.latestAction?.text
      );
    }
  }, [details, open]);

  const handlePrint = () => {
    const title = escapeHtml(bill?.title || "Health Bill");
    const summary = escapeHtml(aiSummary?.plainEnglish || "");
    const impact = escapeHtml(aiSummary?.impact || "");
    const official = escapeHtml(details?.summary ? stripHtml(details.summary) : "");
    const billCode = escapeHtml(`${details?.type?.toUpperCase() || ""}${details?.number || ""}`);
    const congressLabel = details?.congress ? escapeHtml(`${ordinal(details.congress)} Congress`) : "";
    const printWindow = window.open("", "_blank");
    if (printWindow) {
      printWindow.document.write(`
        <html><head><title>${title}</title>
        <style>body{font-family:system-ui,sans-serif;max-width:700px;margin:40px auto;padding:0 20px;color:#1a1a1a}
        h1{font-size:1.4em;margin-bottom:0.5em}h2{font-size:1.1em;margin-top:1.5em;color:#333}
        p{line-height:1.6;color:#444}hr{border:none;border-top:1px solid #ddd;margin:1.5em 0}
        .badge{display:inline-block;background:#f0f0f0;padding:2px 10px;border-radius:12px;font-size:0.85em;margin-right:6px}
        @media print{body{margin:20px}}</style></head><body>
        <h1>${title}</h1>
        <span class="badge">${billCode}</span>
        <span class="badge">${congressLabel}</span>
        ${summary ? `<h2>Plain English Summary</h2><p>${summary}</p>` : ""}
        ${impact ? `<h2>How Does This Affect You?</h2><p>${impact}</p>` : ""}
        ${official ? `<hr><h2>Official Summary</h2><p>${official}</p>` : ""}
        <hr><p style="font-size:0.85em;color:#888">Generated by CivicCare · civiccare.app</p>
        </body></html>`);
      printWindow.document.close();
      printWindow.print();
    }
  };

  const billTypeSlug: Record<string, string> = {
    hr: "house-bill", s: "senate-bill", hres: "house-resolution", sres: "senate-resolution",
    hjres: "house-joint-resolution", sjres: "senate-joint-resolution",
    hconres: "house-concurrent-resolution", sconres: "senate-concurrent-resolution",
  };
  const congressUrl = `https://www.congress.gov/bill/${details?.congress || 119}th-congress/${billTypeSlug[(details?.type || bill?.type || "hr").toLowerCase()] || "house-bill"}/${details?.number || bill?.number || ""}/text`;

  const handleShare = async () => {
    const title = bill?.title || 'Health Bill';
    const text = aiSummary?.plainEnglish || `Check out this health bill: ${title}`;
    const url = congressUrl;

    if (navigator.share) {
      try {
        await navigator.share({ title, text, url });
      } catch (e) {
        // User cancelled
      }
    } else {
      await navigator.clipboard.writeText(`${text}\n${url}`);
      toast({ title: "Copied to clipboard!", description: "Share link copied." });
    }
  };

  return (
    <Dialog open={open} onOpenChange={onOpenChange}>
      <DialogContent className="max-w-2xl max-h-[80vh] overflow-y-auto">
        <DialogHeader>
          <DialogTitle className="text-xl font-bold pr-8">
            {bill?.title || "Bill Details"}
          </DialogTitle>
        </DialogHeader>

        {loading && (
          <div className="space-y-4">
            <Skeleton className="h-6 w-32" />
            <Skeleton className="h-4 w-full" />
            <Skeleton className="h-4 w-full" />
            <Skeleton className="h-4 w-3/4" />
          </div>
        )}

        {error && (
          <div className="text-destructive text-sm py-4">
            Failed to load bill details: {error}
          </div>
        )}

        {!loading && !error && details && (
          <div className="space-y-6">
            {/* Bill ID and Status */}
            <div className="flex flex-wrap gap-2">
              <Badge variant="outline" className="text-sm">
                {details.type?.toUpperCase()}{details.number}
              </Badge>
              <Badge variant="secondary" className="text-sm">
                {details.congress}th Congress
              </Badge>
              {details.policyArea?.name && (
                <Badge className="text-sm bg-primary/10 text-primary">
                  {details.policyArea.name}
                </Badge>
              )}
            </div>

            {/* AI Plain English Summary */}
            <div className="space-y-2 rounded-xl border border-primary/20 bg-primary/5 p-4">
              <h3 className="font-semibold flex items-center gap-2 text-primary">
                <Sparkles className="w-4 h-4" />
                Plain English Summary
              </h3>
              {aiLoading && (
                <div className="space-y-2">
                  <Skeleton className="h-4 w-full" />
                  <Skeleton className="h-4 w-3/4" />
                </div>
              )}
              {aiError && (
                <p className="text-sm text-muted-foreground">Unable to generate summary. {aiError}</p>
              )}
              {aiSummary && (
                <>
                  <p className="text-sm text-foreground leading-relaxed">{aiSummary.plainEnglish}</p>
                  <div className="mt-3 pt-3 border-t border-primary/10">
                    <p className="text-xs font-medium text-muted-foreground uppercase tracking-wide mb-1">How does this affect you?</p>
                    <p className="text-sm text-foreground leading-relaxed">{aiSummary.impact}</p>
                  </div>
                  <p className="mt-3 text-xs text-muted-foreground italic">
                    AI-generated summary — check the{" "}
                    <a
                      href={congressUrl}
                      target="_blank"
                      rel="noopener noreferrer"
                      className="underline text-primary not-italic"
                    >
                      official bill text on Congress.gov
                    </a>
                    .
                  </p>
                </>
              )}
            </div>

            {/* Official Summary */}
            {details.summary && (
              <div className="space-y-2">
                <h3 className="font-semibold flex items-center gap-2">
                  <FileText className="w-4 h-4" />
                  Official Summary
                </h3>
                <p className="text-muted-foreground text-sm leading-relaxed">
                  {stripHtml(details.summary)}
                </p>
              </div>
            )}

            {/* Latest Action */}
            {details.latestAction && (
              <div className="space-y-2">
                <h3 className="font-semibold flex items-center gap-2">
                  <Calendar className="w-4 h-4" />
                  Latest Action
                </h3>
                <div className="bg-secondary/50 rounded-lg p-4">
                  <p className="text-sm font-medium">
                    {details.latestAction.actionDate}
                  </p>
                  <p className="text-muted-foreground text-sm">
                    {details.latestAction.text}
                  </p>
                </div>
              </div>
            )}

            {/* Sponsors */}
            {details.sponsors && details.sponsors.length > 0 && (
              <div className="space-y-2">
                <h3 className="font-semibold flex items-center gap-2">
                  <Users className="w-4 h-4" />
                  Sponsors
                </h3>
                <div className="flex flex-wrap gap-2">
                  {details.sponsors.map((sponsor, idx) => (
                    <span
                      key={idx}
                      className="text-xs px-2.5 py-1 rounded border border-border bg-card text-foreground"
                    >
                      {sponsor.firstName} {sponsor.lastName} ({sponsor.party}-{sponsor.state})
                    </span>
                  ))}
                </div>
                {details.cosponsors && details.cosponsors > 0 && (
                  <p className="text-xs text-muted-foreground">
                    + {details.cosponsors} co-sponsors
                  </p>
                )}
              </div>
            )}

            {/* Actions */}
            <div className="flex gap-2">
              {bill && (
                <Button
                  variant={isTracked(bill.id) ? "default" : "outline"}
                  className="flex-1"
                  onClick={async () => {
                    if (!user) {
                      toast({ title: "Sign in required", description: "Create an account to track bills." });
                      return;
                    }
                    try {
                      const tracked = await toggleTrack(bill);
                      toast({ title: tracked ? "Bill tracked!" : "Bill untracked" });
                    } catch {
                      toast({ title: "Error", variant: "destructive" });
                    }
                  }}
                >
                  <Bookmark className={`w-4 h-4 mr-2 ${isTracked(bill.id) ? "fill-current" : ""}`} />
                  {isTracked(bill.id) ? "Tracking" : "Track Bill"}
                </Button>
              )}
              <Button
                variant="outline"
                onClick={() => window.open(congressUrl, '_blank')}
              >
                <ExternalLink className="w-4 h-4 mr-2" />
                Congress.gov
              </Button>
              <Button variant="outline" onClick={handleShare}>
                <Share2 className="w-4 h-4 mr-2" />
                Share
              </Button>
              <Button variant="outline" onClick={handlePrint} aria-label="Print summary">
                <Printer className="w-4 h-4" aria-hidden="true" />
              </Button>
            </div>

            {/* Community Discussion */}
            <div className="pt-2 border-t border-border">
              <BillDiscussion billId={bill?.id || null} />
            </div>
          </div>
        )}
      </DialogContent>
    </Dialog>
  );
};

export default BillDetailModal;
